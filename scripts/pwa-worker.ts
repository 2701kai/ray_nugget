// Kept separate from export preparation so update tests use the actual worker.
export function pwaWorker(build: string, assets: string[]) {
  return String.raw`// Generated by scripts/prepare-pwa.ts. Public application resources only.
const BUILD = '${build}';
const CACHE = 'pete-shell-' + BUILD;
const OCR = 'pete-ocr-' + BUILD;
const HISTORY = new URL('/.pete-previous-caches', self.location.origin).href;
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const previous = (await caches.keys()).filter(key => /^pete-(?:shell|ocr)-[a-f0-9]{16}$/.test(key) && key !== CACHE && key !== OCR);
    const cache = await caches.open(CACHE);
    try {
      await cache.addAll(ASSETS);
      const html = await (await cache.match('/index.html')).text();
      if (!html.includes('name="pete-build" content="' + BUILD + '"')) throw new Error('Release changed during installation');
      await cache.put(HISTORY, new Response(JSON.stringify(previous)));
      await self.skipWaiting();
    } catch (error) { await caches.delete(CACHE); throw error; }
  })());
});
const builds = new Map();
async function clientBuild(client) {
  const build = await new Promise(resolve => {
    const channel = new MessageChannel();
    const timer = setTimeout(() => { channel.port1.close(); resolve(undefined); }, 1500);
    channel.port1.onmessage = event => {
      clearTimeout(timer); channel.port1.close();
      resolve(typeof event.data?.build === 'string' && /^[a-f0-9]{16}$/.test(event.data.build) ? event.data.build : undefined);
    };
    client.postMessage({ type: 'PETE_BUILD_QUERY' }, [channel.port2]);
  });
  if (build) builds.set(client.id, build);
  return build;
}
let pruning;
function prune() {
  if (pruning) return pruning;
  pruning = (async () => {
    if (self.registration.installing || self.registration.waiting) return;
    const clients = (await self.clients.matchAll({ type: 'window', includeUncontrolled: true }))
      .filter(client => !new URL(client.url).pathname.startsWith('/__/'));
    const versions = await Promise.all(clients.map(clientBuild));
    // Old releases, auth callbacks or suspended tabs may not reply. Retain their
    // resources rather than risk breaking an unfinished capture or offline tab.
    if (versions.some(version => !version)) return;
    const keep = new Set([BUILD, ...versions]);
    // Only remove caches that predate this worker. A still-running older worker
    // must never delete a newer release while it installs or takes control.
    const history = await (await caches.open(CACHE)).match(HISTORY);
    for (const key of history ? await history.json() : []) {
      if (self.registration.installing || self.registration.waiting) return;
      const match = key.match(/^pete-(?:shell|ocr)-([a-f0-9]{16})$/);
      if (match && !keep.has(match[1])) await caches.delete(key);
    }
  })().finally(() => { pruning = undefined; });
  return pruning;
}
self.addEventListener('activate', event => {
  // Change resource routing immediately, but let each page choose when to reload.
  event.waitUntil((async () => { await self.clients.claim(); await prune(); })());
});
self.addEventListener('message', event => {
  if (event.data?.type === 'PETE_VERSION') event.ports[0]?.postMessage({ build: BUILD });
  if (event.data?.type === 'PETE_CLIENT_READY') event.waitUntil(prune());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/__/') || url.pathname.startsWith('/api/')) return;
  if (request.mode === 'navigate') {
    event.respondWith(caches.open(CACHE).then(cache => cache.match('/index.html')).then(cached => cached || fetch(request)));
  } else if (!url.search && (ASSETS.includes(url.pathname) || /^\/(?:_expo|assets)\//.test(url.pathname))) {
    // A busy older tab can still load its own immutable assets after activation.
    event.respondWith((async () => {
      const cached = await (await caches.open(CACHE)).match(request) || await caches.match(request);
      return cached || fetch(request);
    })());
  } else if (!url.search && /^\/ocr\/(?:worker\.min\.js|core\/[a-z0-9.-]+\.(?:js|wasm)|lang\/(?:eng|deu)\.traineddata\.gz)$/.test(url.pathname)) {
    event.respondWith((async () => {
      const client = event.clientId && await self.clients.get(event.clientId);
      const version = builds.get(event.clientId) || (client && await clientBuild(client));
      const cache = await caches.open(version ? 'pete-ocr-' + version : OCR);
      const cached = await cache.match(request) || (!version && await caches.match(request));
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok) await cache.put(request, response.clone());
      return response;
    })());
  }
});
`;
}
